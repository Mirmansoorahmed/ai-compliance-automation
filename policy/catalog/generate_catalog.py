def _emit_scalar(value: str) -> str:
    """Emit a YAML double-quoted scalar on a single line."""
    s = str(value)
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def render_yaml() -> str:
    lines = [f"version: {_emit_scalar(VERSION)}", "checks:"]
    for check in CHECKS:
        first = True
        for key in FIELDS:
            val = check[key]
            prefix = "  - " if first else "    "
            lines.append(f"{prefix}{key}: {_emit_scalar(val)}")
            first = False
    return "\n".join(lines) + "\n"


def main() -> int:
    out = Path(__file__).resolve().parent / "catalog.yaml"
    out.write_text(render_yaml(), encoding="utf-8")
    print(f"wrote {out} with {len(CHECKS)} checks")
    return 0


